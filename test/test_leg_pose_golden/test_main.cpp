// Golden IK vectors for the desktop calibrator's forward kinematics: a fixed
// set of foot targets solved by kinematics::solveLeg with zero offsets, and
// compared with test/golden/leg_pose.txt, which the Go leg view tests read
// (desktop/internal/legview). After a deliberate kinematics change,
// regenerate the file with `SPOODER_WRITE_GOLDEN=1 mise run test` and review
// the diff.
#include <unity.h>
#include <math.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "movement/body.h"
#include "movement/kinematics.h"

using namespace kinematics;

void setUp() {}
void tearDown() {}

static const char *const HEADER =
    "# Spooder leg inverse kinematics: golden vectors.\n"
    "# Generated by test/test_leg_pose_golden from kinematics::solveLeg with zero\n"
    "# offsets; regenerate with SPOODER_WRITE_GOLDEN=1 mise run test after a\n"
    "# deliberate kinematics change.\n"
    "#\n"
    "# One target per line, fields separated by single spaces:\n"
    "#   <name> <x> <y> <z> <coxa> <femur> <tibia>\n"
    "# The target is in the leg frame (origin at the coxa pivot, x outward, z up,\n"
    "# millimetres); the angles are the solved joint angles in degrees. Every\n"
    "# target is reachable without clamping, so forward kinematics of the\n"
    "# angles returns the target.\n"
    "# Lines starting with # are comments.\n";

struct Text
{
  char buf[8192];
  int len;
};

static void add(Text &t, const char *fmt, ...) __attribute__((format(printf, 2, 3)));
static void add(Text &t, const char *fmt, ...)
{
  va_list ap;
  va_start(ap, fmt);
  t.len += vsnprintf(t.buf + t.len, sizeof(t.buf) - t.len, fmt, ap);
  va_end(ap);
  TEST_ASSERT_TRUE_MESSAGE(t.len < (int)sizeof(t.buf), "golden text buffer too small");
}

struct Target
{
  const char *name;
  Vector3 at;
};

// Initialise, calibration, rest and stand poses from body.cpp, and walking
// points of middle and corner legs (gait.cpp, STANCE_DISTANCE 190).
static const Target TARGETS[] = {
    {"initialise_low", Vector3(160, 0, 0)},
    {"initialise_high", Vector3(225, 0, 115)},
    {"calibration", body::CALIBRATION_POSE},
    {"rest", body::REST_POSE},
    {"stand_height_0", Vector3(190, 0, -60)},
    {"stand_height_50", Vector3(190, 0, -145)},
    {"stand_height_100", Vector3(190, 0, -230)},
    {"walk_forward_end", Vector3(190, 60, -145)},
    {"walk_backward_end", Vector3(190, -60, -145)},
    {"walk_swing_lift", Vector3(190, 20, -100)},
    {"walk_corner_push", Vector3(150, -75, -145)},
    {"walk_corner_reach", Vector3(230, 70, -120)},
    {"turn_negative_coxa", Vector3(180, -90, -140)},
    {"far_reach", Vector3(300, 100, -80)},
};

static void buildGolden(Text &t)
{
  add(t, "%s", HEADER);
  for (const Target &target : TARGETS)
  {
    // Reachable without the IK's clamping: the coxa-to-foot distance lies
    // strictly between the femur and tibia limits.
    float l1 = sqrtf(target.at.x * target.at.x + target.at.y * target.at.y) - COXA_LENGTH;
    float h = sqrtf(l1 * l1 + target.at.z * target.at.z);
    TEST_ASSERT_TRUE_MESSAGE(h > TIBIA_LENGTH - FEMUR_LENGTH + 1 && h < TIBIA_LENGTH + FEMUR_LENGTH - 1, target.name);
    JointAngles a;
    TEST_ASSERT_TRUE_MESSAGE(solveLeg(target.at, Vector3(0, 0, 0), a), target.name);
    add(t, "%s %.1f %.1f %.1f %.4f %.4f %.4f\n", target.name, target.at.x, target.at.y, target.at.z, a.coxa,
        a.femur, a.tibia);
  }
}

static void goldenPath(char *out, int size)
{
  const char *file = __FILE__;
  const char *cut = strstr(file, "test/test_leg_pose_golden/");
  int prefix = cut ? (int)(cut - file) : 0;
  snprintf(out, size, "%.*stest/golden/leg_pose.txt", prefix, file);
}

// The calibration pose is 0/90/90 (spooder-leg-kinematics).
void test_calibration_pose_angles()
{
  JointAngles a;
  TEST_ASSERT_TRUE(solveLeg(body::CALIBRATION_POSE, Vector3(0, 0, 0), a));
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 0, a.coxa);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 90, a.femur);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 90, a.tibia);
}

void test_golden_vectors()
{
  static Text t;
  t = {};
  buildGolden(t);

  char path[512];
  goldenPath(path, sizeof(path));
  const char *write = getenv("SPOODER_WRITE_GOLDEN");
  if (write && write[0] == '1')
  {
    FILE *f = fopen(path, "wb");
    TEST_ASSERT_NOT_NULL_MESSAGE(f, "cannot write test/golden/leg_pose.txt");
    fwrite(t.buf, 1, t.len, f);
    fclose(f);
  }

  static char golden[sizeof(t.buf)];
  FILE *f = fopen(path, "rb");
  TEST_ASSERT_NOT_NULL_MESSAGE(f, "cannot read test/golden/leg_pose.txt");
  int n = (int)fread(golden, 1, sizeof(golden) - 1, f);
  fclose(f);
  golden[n] = 0;
  TEST_ASSERT_EQUAL_STRING(golden, t.buf);
}

int main()
{
  UNITY_BEGIN();
  RUN_TEST(test_calibration_pose_angles);
  RUN_TEST(test_golden_vectors);
  return UNITY_END();
}
