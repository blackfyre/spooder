// Golden gesture previews for the handheld's gesture overlay: for each
// gesture id, whether it has a script, and for a scripted one the joint
// angles gesture::Player produces from the standing point at body height 0,
// sampled every 50 ms and solved as the body solves them
// (kinematics::solveLegInRange with the default calibration's offsets), less
// those offsets: the commanded angles a pose frame carries.
// Compared with test/golden/gestures.txt, from which the handheld's Go table
// is generated (desktop/handheld/internal/gestures). After a deliberate
// change of a script, its timing, the IK or the default offsets, regenerate
// the file with `SPOODER_WRITE_GOLDEN=1 mise run test`, review the diff and
// regenerate the Go table. SPOODER_GESTURES_GOLDEN names another copy of the
// file (to check that a changed value fails the test).
#include <unity.h>
#include <math.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "movement/body.h"
#include "movement/gait.h"
#include "movement/gesture.h"
#include "movement/joint_calibration.h"
#include "movement/kinematics.h"

using namespace gesture;

void setUp() {}
void tearDown() {}

constexpr uint32_t STEP_MS = 50;
// A preview ends at completion or at the first held pose (ball).
constexpr uint32_t MAX_PREVIEW_MS = 10000;

// One token per gesture id, as the golden file names them (fields are
// separated by single spaces). Index 0 is no gesture and is not listed.
static const char *const NAMES[GESTURE_ID_COUNT] = {"none", "say_hi", "wiggle", "dance", "attack", "ball"};

static const char *const HEADER = "# Spooder gestures: golden previews.\n"
                                  "# Generated by test/test_gesture_golden from gesture::Player; regenerate with\n"
                                  "# SPOODER_WRITE_GOLDEN=1 mise run test after a deliberate change of a script,\n"
                                  "# its timing, the IK or the default calibration, then regenerate the\n"
                                  "# handheld's table (go generate ./internal/gestures in desktop/handheld).\n"
                                  "#\n"
                                  "# For each gesture id 1 to 5, in order, one line, fields separated by single\n"
                                  "# spaces:\n"
                                  "#   gesture <id> <name> scripted|none\n"
                                  "# scripted exactly when the robot has a script for it. A scripted gesture is\n"
                                  "# followed by its poses, one line each:\n"
                                  "#   pose <id> <t_ms> <18 joint angles>\n"
                                  "# the commanded joint angles in degrees, leg 0 to 5, coxa femur tibia each,\n"
                                  "# as a pose frame carries them: the player started with every foot at the\n"
                                  "# standing point at body height 0, sampled at t = 0 and every 50 ms until\n"
                                  "# done or holding (the last sample included), each foot solved by\n"
                                  "# kinematics::solveLegInRange with the default calibration's offsets for its\n"
                                  "# leg, as the body solves it, and the offsets then taken off again.\n"
                                  "# Lines starting with # are comments.\n";

struct Text
{
  char buf[131072];
  int len;
};

static void add(Text &t, const char *fmt, ...) __attribute__((format(printf, 2, 3)));
static void add(Text &t, const char *fmt, ...)
{
  va_list ap;
  va_start(ap, fmt);
  t.len += vsnprintf(t.buf + t.len, sizeof(t.buf) - t.len, fmt, ap);
  va_end(ap);
  TEST_ASSERT_TRUE_MESSAGE(t.len < (int)sizeof(t.buf), "golden text buffer too small");
}

// v rounded to two decimals, a rounded -0 written as 0.
static double commanded(float v)
{
  double r = round(v * 100.0) / 100.0;
  return r == 0 ? 0.0 : r;
}

static void addPose(Text &t, int id, uint32_t tMs, const Vector3 *targets, const Vector3 *offsets)
{
  add(t, "pose %d %u", id, (unsigned)tMs);
  for (int leg = 0; leg < LEG_COUNT; leg++)
  {
    Vector3 target = targets[leg];
    kinematics::JointAngles a;
    char msg[64];
    snprintf(msg, sizeof(msg), "gesture %d leg %d at %u ms: target refused", id, leg, (unsigned)tMs);
    TEST_ASSERT_TRUE_MESSAGE(kinematics::solveLegInRange(target, offsets[leg], a), msg);
    // The commanded angles: the solution less the offsets, as the pose
    // frame's commanded field carries them (link_receiver).
    add(t, " %.2f %.2f %.2f", commanded(a.coxa - offsets[leg].x), commanded(a.femur - offsets[leg].y),
        commanded(a.tibia - offsets[leg].z));
  }
  add(t, "\n");
}

static void buildGolden(Text &t)
{
  joint_calibration::Table defaults;
  joint_calibration::loadDefaults(defaults);
  Vector3 offsets[LEG_COUNT];
  for (int leg = 0; leg < LEG_COUNT; leg++)
    offsets[leg] = joint_calibration::legOffsets(defaults, leg);
  const Vector3 standing(gait::STANCE_DISTANCE, 0, body::groundForHeight(0));

  add(t, "%s", HEADER);
  for (int id = 1; id < GESTURE_ID_COUNT; id++)
  {
    bool scripted = available((uint8_t)id);
    add(t, "gesture %d %s %s\n", id, NAMES[id], scripted ? "scripted" : "none");
    if (!scripted)
      continue;

    Vector3 feet[LEG_COUNT];
    for (int leg = 0; leg < LEG_COUNT; leg++)
      feet[leg] = standing;
    static Player p;
    p = Player();
    start(p, (Gesture)id, feet, standing);
    Vector3 targets[LEG_COUNT];
    advance(p, 0, standing, targets);
    addPose(t, id, 0, targets, offsets);
    uint32_t tMs = 0;
    while (!p.done && p.stage != Stage::Holding)
    {
      char msg[64];
      snprintf(msg, sizeof(msg), "gesture %d not done within %u ms", id, (unsigned)MAX_PREVIEW_MS);
      TEST_ASSERT_TRUE_MESSAGE(tMs + STEP_MS <= MAX_PREVIEW_MS, msg);
      advance(p, STEP_MS, standing, targets);
      tMs += STEP_MS;
      addPose(t, id, tMs, targets, offsets);
    }
  }
}

static void goldenPath(char *out, int size)
{
  const char *override = getenv("SPOODER_GESTURES_GOLDEN");
  if (override && override[0])
  {
    snprintf(out, size, "%s", override);
    return;
  }
  const char *file = __FILE__;
  const char *cut = strstr(file, "test/test_gesture_golden/");
  int prefix = cut ? (int)(cut - file) : 0;
  snprintf(out, size, "%.*stest/golden/gestures.txt", prefix, file);
}

// Say hi, wiggle and provisional ball have scripts; dance and attack do not. A
// script landing for one of them changes this test with the golden file.
void test_scripted_ids()
{
  TEST_ASSERT_TRUE(available(1));
  TEST_ASSERT_TRUE(available(2));
  TEST_ASSERT_FALSE(available(3));
  TEST_ASSERT_FALSE(available(4));
  TEST_ASSERT_TRUE(available(5));
}

void test_golden_previews()
{
  static Text t;
  t = {};
  buildGolden(t);

  char path[512];
  goldenPath(path, sizeof(path));
  const char *write = getenv("SPOODER_WRITE_GOLDEN");
  if (write && write[0] == '1')
  {
    FILE *f = fopen(path, "wb");
    TEST_ASSERT_NOT_NULL_MESSAGE(f, "cannot write test/golden/gestures.txt");
    fwrite(t.buf, 1, t.len, f);
    fclose(f);
  }

  static char golden[sizeof(t.buf)];
  FILE *f = fopen(path, "rb");
  TEST_ASSERT_NOT_NULL_MESSAGE(f, "cannot read test/golden/gestures.txt");
  int n = (int)fread(golden, 1, sizeof(golden) - 1, f);
  fclose(f);
  golden[n] = 0;
  TEST_ASSERT_EQUAL_STRING(golden, t.buf);
}

int main()
{
  UNITY_BEGIN();
  RUN_TEST(test_scripted_ids);
  RUN_TEST(test_golden_previews);
  return UNITY_END();
}
