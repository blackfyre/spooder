// The body geometry: each leg's coxa pivot and mount angle, and the body's
// underside, compared with test/golden/body_geometry.txt, which the Go leg
// view tests read
// (desktop/internal/legview). After a deliberate geometry change, regenerate
// the file with `SPOODER_WRITE_GOLDEN=1 mise run test` and review the diff.
#include <unity.h>
#include <math.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "movement/body_geometry.h"
#include "movement/gait.h"

using body_geometry::PIVOTS;
using kinematics::LEG_COUNT;

void setUp() {}
void tearDown() {}

static const char *const HEADER = "# Spooder body geometry: golden values.\n"
                                  "# Generated by test/test_body_geometry from core/movement/body_geometry and\n"
                                  "# gait::mountAngleDeg; regenerate with SPOODER_WRITE_GOLDEN=1 mise run test\n"
                                  "# after a deliberate geometry change.\n"
                                  "#\n"
                                  "# One leg per line, in servo output order, fields separated by single spaces:\n"
                                  "#   <leg> <x> <y> <z> <mount angle>\n"
                                  "# The coxa pivot is in the body frame (x right, y forward, z up, millimetres,\n"
                                  "# origin at the frame's centre); the mount angle is the leg frame's x axis,\n"
                                  "# in degrees anticlockwise from +x.\n"
                                  "# Then one line for the body's underside, its lowest point (body frame z,\n"
                                  "# millimetres, below the pivots' z = 0):\n"
                                  "#   underside <z>\n"
                                  "# Lines starting with # are comments.\n";

struct Text
{
  char buf[2048];
  int len;
};

static void add(Text &t, const char *fmt, ...) __attribute__((format(printf, 2, 3)));
static void add(Text &t, const char *fmt, ...)
{
  va_list ap;
  va_start(ap, fmt);
  t.len += vsnprintf(t.buf + t.len, sizeof(t.buf) - t.len, fmt, ap);
  va_end(ap);
  TEST_ASSERT_TRUE_MESSAGE(t.len < (int)sizeof(t.buf), "golden text buffer too small");
}

static void goldenPath(char *out, int size)
{
  const char *file = __FILE__;
  const char *cut = strstr(file, "test/test_body_geometry/");
  int prefix = cut ? (int)(cut - file) : 0;
  snprintf(out, size, "%.*stest/golden/body_geometry.txt", prefix, file);
}

// Each pivot lies on its leg's mount angle from the centre, as the frame's
// holes do, and the body is mirror-symmetric about the y axis.
void test_pivots_lie_on_their_mount_angles()
{
  for (int leg = 0; leg < LEG_COUNT; leg++)
  {
    const Vector3 &p = PIVOTS[leg];
    float a = gait::mountAngleDeg(leg) * (float)M_PI / 180.0f;
    float r = sqrtf(p.x * p.x + p.y * p.y);
    TEST_ASSERT_FLOAT_WITHIN(0.02f, r * cosf(a), p.x);
    TEST_ASSERT_FLOAT_WITHIN(0.02f, r * sinf(a), p.y);
    TEST_ASSERT_EQUAL_FLOAT(0, p.z);
    const Vector3 &mirror = PIVOTS[LEG_COUNT - 1 - leg];
    TEST_ASSERT_EQUAL_FLOAT(-p.x, mirror.x);
    TEST_ASSERT_EQUAL_FLOAT(p.y, mirror.y);
  }
}

// The underside lies below the pivots, and below Frame Bottom's underside
// (15.75 mm), since the coxa links under the pivots reach lower.
void test_underside_lies_below_the_frame_bottom()
{
  TEST_ASSERT_TRUE(body_geometry::UNDERSIDE_Z < -15.75f);
  TEST_ASSERT_TRUE(body_geometry::UNDERSIDE_Z > -60); // above the feet at body height 0
}

void test_golden_values()
{
  static Text t;
  t = {};
  add(t, "%s", HEADER);
  for (int leg = 0; leg < LEG_COUNT; leg++)
    add(t, "%d %.2f %.2f %.2f %.4f\n", leg, PIVOTS[leg].x, PIVOTS[leg].y, PIVOTS[leg].z, gait::mountAngleDeg(leg));
  add(t, "underside %.2f\n", body_geometry::UNDERSIDE_Z);

  char path[512];
  goldenPath(path, sizeof(path));
  const char *write = getenv("SPOODER_WRITE_GOLDEN");
  if (write && write[0] == '1')
  {
    FILE *f = fopen(path, "wb");
    TEST_ASSERT_NOT_NULL_MESSAGE(f, "cannot write test/golden/body_geometry.txt");
    fwrite(t.buf, 1, t.len, f);
    fclose(f);
  }

  static char golden[sizeof(t.buf)];
  FILE *f = fopen(path, "rb");
  TEST_ASSERT_NOT_NULL_MESSAGE(f, "cannot read test/golden/body_geometry.txt");
  int n = (int)fread(golden, 1, sizeof(golden) - 1, f);
  fclose(f);
  golden[n] = 0;
  TEST_ASSERT_EQUAL_STRING(golden, t.buf);
}

int main()
{
  UNITY_BEGIN();
  RUN_TEST(test_pivots_lie_on_their_mount_angles);
  RUN_TEST(test_underside_lies_below_the_frame_bottom);
  RUN_TEST(test_golden_values);
  return UNITY_END();
}
