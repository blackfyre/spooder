// Package gestures is the handheld's copy of the robot's gesture previews:
// which gestures have a script, and the joint angles the robot's own player
// produces through each, every StepMs. Table is generated from
// test/golden/gestures.txt (written by test/test_gesture_golden from
// gesture::Player); its test fails when the two differ (design D2).
package gestures

//go:generate go run ./gen

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"math"
	"strconv"
	"strings"

	"github.com/blackfyre/spooder/desktop/internal/protocol"
)

// StepMs is the time between two frames of a preview, as sampled by the
// golden test.
const StepMs = 50

// Joints is the number of angles in a frame: leg 0 to 5, coxa femur tibia
// each.
const Joints = 18

// maxAngle bounds a joint angle in degrees, the servos' range.
const maxAngle = 180

// Gesture is one gesture id's preview.
type Gesture struct {
	ID       uint8  // protocol.Gesture* id
	Name     string // the golden file's token, such as "say_hi"
	Scripted bool   // the robot has a script for it
	StepMs   int    // time between frames
	// Frames are the commanded joint angles in degrees from t = 0, one every
	// StepMs, the last one the script's end; none when not scripted.
	Frames [][Joints]float32
}

// Parse reads the golden text: for each id 1 to protocol.GestureCount-1 in
// order a "gesture <id> <name> scripted|none" line, a scripted one followed
// by at least one "pose <id> <t_ms> <18 angles>" line, t_ms 0 and then
// every StepMs. Blank lines and lines starting with # are skipped.
func Parse(r io.Reader) ([]Gesture, error) {
	var out []Gesture
	sc := bufio.NewScanner(r)
	line := 0
	for sc.Scan() {
		line++
		text := sc.Text()
		if text == "" || strings.HasPrefix(text, "#") {
			continue
		}
		f := strings.Split(text, " ")
		var err error
		switch f[0] {
		case "gesture":
			out, err = parseGesture(out, f)
		case "pose":
			err = parsePose(out, f)
		default:
			err = fmt.Errorf("unknown record %q", f[0])
		}
		if err != nil {
			return nil, fmt.Errorf("line %d: %w", line, err)
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if err := checkLast(out); err != nil {
		return nil, err
	}
	if len(out) != protocol.GestureCount-1 {
		return nil, fmt.Errorf("%d gestures, want %d", len(out), protocol.GestureCount-1)
	}
	return out, nil
}

func checkLast(gs []Gesture) error {
	if n := len(gs); n > 0 && gs[n-1].Scripted && len(gs[n-1].Frames) == 0 {
		return fmt.Errorf("gesture %d is scripted without poses", gs[n-1].ID)
	}
	return nil
}

func parseGesture(gs []Gesture, f []string) ([]Gesture, error) {
	if len(f) != 4 {
		return nil, fmt.Errorf("gesture: %d fields, want 4", len(f))
	}
	if err := checkLast(gs); err != nil {
		return nil, err
	}
	want := len(gs) + 1
	id, err := strconv.Atoi(f[1])
	if err != nil || id != want {
		return nil, fmt.Errorf("gesture id %q, want %d", f[1], want)
	}
	if !validName(f[2]) {
		return nil, fmt.Errorf("gesture name %q", f[2])
	}
	g := Gesture{ID: uint8(id), Name: f[2], StepMs: StepMs}
	switch f[3] {
	case "scripted":
		g.Scripted = true
	case "none":
	default:
		return nil, fmt.Errorf("gesture availability %q", f[3])
	}
	return append(gs, g), nil
}

// validName accepts a lower-case token of letters, digits and underscores.
func validName(s string) bool {
	if s == "" {
		return false
	}
	for _, c := range s {
		if (c < 'a' || c > 'z') && (c < '0' || c > '9') && c != '_' {
			return false
		}
	}
	return true
}

func parsePose(gs []Gesture, f []string) error {
	if len(f) != 3+Joints {
		return fmt.Errorf("pose: %d fields, want %d", len(f), 3+Joints)
	}
	if len(gs) == 0 {
		return fmt.Errorf("pose before any gesture")
	}
	g := &gs[len(gs)-1]
	if f[1] != strconv.Itoa(int(g.ID)) {
		return fmt.Errorf("pose id %q, want %d", f[1], g.ID)
	}
	if !g.Scripted {
		return fmt.Errorf("pose for gesture %d, which has no script", g.ID)
	}
	if want := strconv.Itoa(len(g.Frames) * StepMs); f[2] != want {
		return fmt.Errorf("pose time %q, want %s", f[2], want)
	}
	var fr [Joints]float32
	for i := range fr {
		v, err := strconv.ParseFloat(f[3+i], 32)
		if err != nil || math.IsNaN(v) || v < 0 || v > maxAngle {
			return fmt.Errorf("angle %q", f[3+i])
		}
		fr[i] = float32(v)
	}
	g.Frames = append(g.Frames, fr)
	return nil
}

// Format writes gs as the Go source of table_gen.go, gofmt'd.
func Format(gs []Gesture) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./gen from test/golden/gestures.txt; DO NOT EDIT.\n\n")
	b.WriteString("package gestures\n\n")
	b.WriteString("// Table is every gesture id's preview, in id order.\n")
	b.WriteString("var Table = [...]Gesture{\n")
	for _, g := range gs {
		fmt.Fprintf(&b, "{ID: %d, Name: %q, Scripted: %t, StepMs: %d", g.ID, g.Name, g.Scripted, g.StepMs)
		if len(g.Frames) > 0 {
			b.WriteString(", Frames: [][Joints]float32{\n")
			for _, fr := range g.Frames {
				b.WriteString("{")
				for i, v := range fr {
					if i > 0 {
						b.WriteString(", ")
					}
					b.WriteString(strconv.FormatFloat(float64(v), 'f', -1, 32))
				}
				b.WriteString("},\n")
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
