"""Generates the bridge screen's smooth fonts (LovyanGFX VLW data as C arrays).

Run by hand from the repository root when the fonts or sizes change; the
build uses the checked-in headers:

    uv run firmware/bridge/scripts/make_fonts.py

The TTFs are the desktop calibrator's copies (SIL OFL 1.1). The VLW layout
is Processing's, as LovyanGFX's VLWfont::loadFont reads it: a header of six
big-endian int32 (glyph count, version, size, 0, ascent, descent), one record
of seven per glyph (code point, height, width, x advance, top above the
baseline, left offset, 0), then each glyph's 8-bit alpha bitmap.
"""

import shutil
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[3]
FONT_DIR = ROOT / "desktop/internal/ui/fonts"
OUT_DIR = ROOT / "firmware/bridge/main/fonts"

# Printable ASCII and the middle dot.
CODE_POINTS = list(range(0x20, 0x7F)) + [0xB7]

FONTS = [
    ("MONO_10", "JetBrainsMono-Regular.ttf", 10),
    ("MONO_12", "JetBrainsMono-Regular.ttf", 12),
    ("SANS_14", "Archivo-SemiBold.ttf", 14),
    ("SANS_22", "Archivo-SemiBold.ttf", 22),
]
LICENCES = ["JetBrainsMono-OFL.txt", "Archivo-OFL.txt"]


def vlw(ttf: Path, size: int) -> bytes:
    font = ImageFont.truetype(str(ttf), size)
    ascent, descent = font.getmetrics()
    records, bitmaps = [], []
    for cp in CODE_POINTS:
        ch = chr(cp)
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        width, height = max(right - left, 0), max(bottom - top, 0)
        advance = round(font.getlength(ch))
        bitmap = b""
        if width and height:
            img = Image.new("L", (width, height), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
            bitmap = img.tobytes()
        records.append(struct.pack(">7i", cp, height, width, advance, -top, left, 0))
        bitmaps.append(bitmap)
    header = struct.pack(">6i", len(CODE_POINTS), 11, size, 0, ascent, descent)
    return header + b"".join(records) + b"".join(bitmaps)


def header(name: str, source: str, size: int, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
    body = ",\n  ".join(rows)
    return (
        f"// Generated by firmware/bridge/scripts/make_fonts.py from {source} at {size} px\n"
        f"// (SIL OFL 1.1, see the licence beside it). Do not edit.\n"
        f"#pragma once\n#include <stdint.h>\n\n"
        f"namespace fonts\n{{\n\nconstexpr uint8_t {name}[] = {{\n  {body}\n}};\n\n}} // namespace fonts\n"
    )


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, ttf, size in FONTS:
        data = vlw(FONT_DIR / ttf, size)
        (OUT_DIR / f"{name.lower()}.h").write_text(header(name, ttf, size, data))
        print(f"{name}: {len(data)} bytes")
    for licence in LICENCES:
        shutil.copyfile(FONT_DIR / licence, OUT_DIR / licence)


if __name__ == "__main__":
    main()
